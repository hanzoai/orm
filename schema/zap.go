// EmitZAP compiles every PlaneZAP entity in r into canonical `.zap` IDL
// compatible with github.com/zap-proto/go/idl (`zapgen`).
//
// Structured `# @entity` and `# @field` comment directives preserve storage,
// tenancy, ClickHouse engine, and governance metadata without breaking
// `zapgen` (which ignores `#` comments as whitespace), enabling lossless
// round-trips via ParseZAP.
func (r *Registry) EmitZAP() (string, error) {
	if err := r.Validate(); err != nil {
		return "", err
	}
	pkg := r.Namespace
	if pkg == "" {
		pkg = "hanzo.schema"
	}

	var sb strings.Builder
	sb.WriteString("# Code generated by github.com/hanzoai/orm/schema. DO NOT EDIT.\n")
	fmt.Fprintf(&sb, "# Schema fingerprint: %s\n", r.Fingerprint()[:16])
	fmt.Fprintf(&sb, "package %s\n", pkg)

	for _, e := range r.entities {
		if !e.Planes.Has(PlaneZAP) {
			continue
		}
		sb.WriteByte('\n')
		writeEntityZAP(&sb, e)
	}
	return sb.String(), nil
}

// EmitZAP compiles a single Entity into canonical `zap/go/idl` `.zap` source.
func (e *Entity) EmitZAP() (string, error) {
	if err := e.Validate(); err != nil {
		return "", err
	}
	pkg := e.ZAPPackage
	if pkg == "" {
		pkg = "hanzo.schema"
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "package %s\n\n", pkg)
	writeEntityZAP(&sb, e)
	return sb.String(), nil
}

func writeEntityZAP(sb *strings.Builder, e *Entity) {
	// Emit lossless metadata directive as a `#` comment.
	var meta []string
	meta = append(meta, "kind="+string(e.Kind))
	meta = append(meta, "planes="+e.Planes.String())
	if e.SQLSchema != "" && e.SQLSchema != "public" {
		meta = append(meta, "sql_schema="+e.SQLSchema)
	}
	if e.SQLTable != "" {
		meta = append(meta, "sql_table="+e.SQLTable)
	}
	if e.DatastoreDB != "" {
		meta = append(meta, "datastore_db="+e.DatastoreDB)
	}
	if e.DatastoreTable != "" {
		meta = append(meta, "datastore_table="+e.DatastoreTable)
	}
	if e.Tenant.Isolated {
		tc := e.tenantColumn()
		if e.Tenant.RLS {
			meta = append(meta, "tenant="+tc+":rls")
		} else {
			meta = append(meta, "tenant="+tc)
		}
	}
	if e.Catalog.Domain != "" {
		meta = append(meta, "domain="+e.Catalog.Domain)
	}
	if e.Catalog.Financial {
		meta = append(meta, "financial=true")
	}
	if e.Catalog.Retention != "" {
		meta = append(meta, "retention="+strings.ReplaceAll(e.Catalog.Retention, " ", "%20"))
	}
	if e.Catalog.FreshnessTargetMS > 0 {
		meta = append(meta, fmt.Sprintf("freshness_ms=%d", e.Catalog.FreshnessTargetMS))
	}
	if e.Catalog.Accuracy != "" {
		meta = append(meta, "accuracy="+e.Catalog.Accuracy)
	}
	if len(e.OrderBy) > 0 {
		meta = append(meta, "order_by="+strings.Join(e.OrderBy, "+"))
	}
	if e.VersionCol != "" {
		meta = append(meta, "version_col="+e.VersionCol)
	}
	if e.TTL != "" {
		meta = append(meta, "ttl="+strings.ReplaceAll(e.TTL, " ", "%20"))
	}
	fmt.Fprintf(sb, "# @entity %s\n", strings.Join(meta, " "))
	fmt.Fprintf(sb, "struct %s {\n", e.Name)

	offset := 0
	for _, f := range e.Fields {
		zt, align, size := zapIDLType(f.Type)
		if align > 1 {
			if rem := offset % align; rem != 0 {
				offset += align - rem
			}
		}
		zapName := f.GoName
		if zapName == "" {
			zapName = toPascal(f.Name)
		}
		if fMeta := fieldAnnotation(f, zapName); fMeta != "" {
			fmt.Fprintf(sb, "    # @field %s\n", fMeta)
		}
		fmt.Fprintf(sb, "    %s %s @%d\n", zapName, zt, offset)
		offset += size
	}
	sb.WriteString("}\n")
}

func fieldAnnotation(f Field, zapName string) string {
	var parts []string
	if toSnake(zapName) != f.Name {
		parts = append(parts, "name="+f.Name)
	}
	// Preserve semantic types that widen to a shared wire primitive (e.g. money_minor -> i64).
	switch f.Type {
	case TypeLowCardString, TypeMoneyMinor, TypeMoneyNano, TypeTimestamp, TypeDate, TypeJSON:
		parts = append(parts, "type="+string(f.Type))
	}
	if f.PrimaryKey {
		parts = append(parts, "pk")
	}
	if f.Nullable {
		parts = append(parts, "nullable")
	}
	if f.Unique {
		parts = append(parts, "unique")
	}
	if f.Indexed {
		parts = append(parts, "index")
	}
	if f.Version {
		parts = append(parts, "version")
	}
	if f.Timestamp {
		parts = append(parts, "timestamp")
	}
	if f.Partition {
		parts = append(parts, "partition")
	}
	if f.OrderRank > 0 {
		parts = append(parts, fmt.Sprintf("order=%d", f.OrderRank))
	}
	if f.Sign {
		parts = append(parts, "sign")
	}
	if f.Tombstone {
		parts = append(parts, "tombstone")
	}
	if f.PII {
		parts = append(parts, "pii")
	}
	if f.Unit != "" {
		parts = append(parts, "unit="+f.Unit)
	}
	if f.Default != "" {
		parts = append(parts, "default="+f.Default)
	}
	return strings.Join(parts, " ")
}

// EmitZAPCapnp compiles every PlaneZAP entity in r into the Cap'n-style `.zap`
// syntax consumed directly by `hanzoai/zap/zapc-rs` (Rust `zapwire` codegen).
func (r *Registry) EmitZAPCapnp() (string, error) {
	if err := r.Validate(); err != nil {
		return "", err
	}
	h := fnv.New64a()
	_, _ = h.Write([]byte(r.Namespace))
	fileID := h.Sum64() | (1 << 63)

	var sb strings.Builder
	fmt.Fprintf(&sb, "@0x%016x;\n\n", fileID)
	sb.WriteString("# Code generated by github.com/hanzoai/orm/schema for zapc-rs.\n")
	fmt.Fprintf(&sb, "# Schema fingerprint: %s\n", r.Fingerprint()[:16])

	for _, e := range r.entities {
		if !e.Planes.Has(PlaneZAP) {
			continue
		}
		fmt.Fprintf(&sb, "\nstruct %s {\n", e.Name)
		for i, f := range e.Fields {
			ord := i
			if f.ZAPOrdinal > 0 {
				ord = f.ZAPOrdinal - 1
			}
			fmt.Fprintf(&sb, "    %s @%d :%s;\n", toCamel(f.Name), ord, zapCapnpType(f.Type))
		}
		sb.WriteString("}\n")
	}
	return sb.String(), nil
}

// zapIDLType maps FieldType to (zap/go/idl type name, byte alignment, slot size).
func zapIDLType(ft FieldType) (string, int, int) {
	switch ft {
	case TypeBool:
		return "bool", 1, 1
	case TypeInt8:
		return "i8", 1, 1
	case TypeUint8:
		return "u8", 1, 1
	case TypeInt16:
		return "i16", 2, 2
	case TypeUint16:
		return "u16", 2, 2
	case TypeInt32, TypeDate:
		return "i32", 4, 4
	case TypeUint32:
		return "u32", 4, 4
	case TypeFloat32:
		return "f32", 4, 4
	case TypeInt64, TypeMoneyMinor, TypeMoneyNano, TypeTimestamp:
		return "i64", 8, 8
	case TypeUint64:
		return "u64", 8, 8
	case TypeFloat64:
		return "f64", 8, 8
	case TypeBytes:
		return "bytes", 4, 8
	case TypeStringArray:
		return "list<text>", 4, 8
	case TypeString, TypeLowCardString, TypeJSON:
		return "text", 4, 8
	default:
		return "text", 4, 8
	}
}

func zapCapnpType(ft FieldType) string {
	switch ft {
	case TypeBool:
		return "Bool"
	case TypeInt8:
		return "Int8"
	case TypeUint8:
		return "UInt8"
	case TypeInt16:
		return "Int16"
	case TypeUint16:
		return "UInt16"
	case TypeInt32, TypeDate:
		return "Int32"
	case TypeUint32:
		return "UInt32"
	case TypeFloat32:
		return "Float32"
	case TypeInt64, TypeMoneyMinor, TypeMoneyNano, TypeTimestamp:
		return "Int64"
	case TypeUint64:
		return "UInt64"
	case TypeFloat64:
		return "Float64"
	case TypeBytes, TypeStringArray:
		return "Data"
	default:
		return "Text"
	}
}

var (
	reZAPPackage    = regexp.MustCompile(`^package\s+([A-Za-z_][A-Za-z0-9_.]*)$`)
	reZAPStructOpen = regexp.MustCompile(`^struct\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{?$`)
	reZAPGoField    = regexp.MustCompile(`^([A-Za-z_][A-Za-z0-9_]*)\s+([A-Za-z0-9_<>]+)(?:\s+@(\d+))?$`)
	reZAPCapnpField = regexp.MustCompile(`^([A-Za-z_][A-Za-z0-9_]*)\s+@(\d+)\s*:([A-Za-z0-9_]+)\s*;?$`)
)

// ParseZAP parses a `.zap` IDL file (either `zap/go/idl` or `zapc-rs` syntax,
// with optional `# @entity` / `# @field` annotations) into a validated Registry
// ready to compile to hanzoai/sql, hanzoai/datastore, and Analytics Catalog.
func ParseZAP(src string) (*Registry, error) {
	reg := NewRegistry("hanzo.schema")

	lines := strings.Split(src, "\n")
	var pendingEntityMeta string
	var pendingFieldMeta string
	var cur *Entity

	flushEntity := func() error {
		if cur == nil {
			return nil
		}
		if cur.SQLTable == "" {
			cur.SQLTable = toSnake(cur.Name)
		}
		if cur.DatastoreDB == "" {
			cur.DatastoreDB = "analytics"
		}
		if cur.DatastoreTable == "" {
			cur.DatastoreTable = cur.defaultDatastoreTable()
		}
		// Ensure bare .zap structs without @entity annotations still have valid defaults.
		if cur.Planes.Has(PlaneSQL) && len(cur.PrimaryKeys()) == 0 && len(cur.Fields) > 0 {
			cur.Fields[0].PrimaryKey = true
		}
		if cur.Planes.Has(PlaneDatastore) && (cur.Kind == KindDim || cur.Kind == KindState) && cur.ResolvedVersionCol() == "" {
			// Fall back to KindFact if an unannotated ZAP struct has no version column.
			cur.Kind = KindFact
			if cur.DatastoreTable == "state_"+toSnake(cur.Name) {
				cur.DatastoreTable = "fact_" + toSnake(cur.Name)
			}
		}
		if err := reg.Register(cur); err != nil {
			return err
		}
		cur = nil
		return nil
	}

	for lineNo, rawLine := range lines {
		line := strings.TrimSpace(rawLine)
		if line == "" {
			continue
		}
		// File ID line in zapc-rs syntax (`@0x...;`).
		if strings.HasPrefix(line, "@0x") {
			continue
		}
		if strings.HasPrefix(line, "#") || strings.HasPrefix(line, "//") {
			comment := strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(line, "#"), "//"))
			if strings.HasPrefix(comment, "@entity ") {
				pendingEntityMeta = strings.TrimSpace(strings.TrimPrefix(comment, "@entity "))
			} else if strings.HasPrefix(comment, "@field ") {
				pendingFieldMeta = strings.TrimSpace(strings.TrimPrefix(comment, "@field "))
			}
			continue
		}
		if m := reZAPPackage.FindStringSubmatch(line); len(m) == 2 {
			reg.Namespace = m[1]
			continue
		}
		if line == "}" {
			if err := flushEntity(); err != nil {
				return nil, fmt.Errorf("zap:%d: %w", lineNo+1, err)
			}
			pendingFieldMeta = ""
			continue
		}
		if m := reZAPStructOpen.FindStringSubmatch(line); len(m) == 2 {
			if cur != nil {
				if err := flushEntity(); err != nil {
					return nil, fmt.Errorf("zap:%d: %w", lineNo+1, err)
				}
			}
			cur = &Entity{
				Name:        m[1],
				Kind:        KindState,
				Planes:      PlaneAll,
				SQLSchema:   "public",
				DatastoreDB: "analytics",
				ZAPPackage:  reg.Namespace,
			}
			if pendingEntityMeta != "" {
				if err := applyEntityAnnotation(cur, pendingEntityMeta); err != nil {
					return nil, fmt.Errorf("zap:%d: %w", lineNo+1, err)
				}
				pendingEntityMeta = ""
			}
			continue
		}

		if cur == nil {
			continue
		}

		// Parse field inside struct (either zapc-rs or zap/go/idl form).
		var f Field
		if m := reZAPCapnpField.FindStringSubmatch(line); len(m) == 4 {
			ord, _ := strconv.Atoi(m[2])
			f = Field{
				Name:       toSnake(m[1]),
				GoName:     toPascal(toSnake(m[1])),
				Type:       zapTypeToFieldType(m[3]),
				ZAPOrdinal: ord + 1,
			}
		} else if m := reZAPGoField.FindStringSubmatch(line); len(m) == 4 {
			f = Field{
				Name:   toSnake(m[1]),
				GoName: toPascal(toSnake(m[1])),
				Type:   zapTypeToFieldType(m[2]),
			}
		} else {
			return nil, fmt.Errorf("zap:%d: cannot parse field %q", lineNo+1, line)
		}

		if pendingFieldMeta != "" {
			if err := applyFieldAnnotation(&f, pendingFieldMeta); err != nil {
				return nil, fmt.Errorf("zap:%d: %w", lineNo+1, err)
			}
			pendingFieldMeta = ""
		}
		cur.Fields = append(cur.Fields, f)
	}

	if cur != nil {
		if err := flushEntity(); err != nil {
			return nil, err
		}
	}
	return reg, nil
}

func applyEntityAnnotation(e *Entity, meta string) error {
	for _, tok := range strings.Fields(meta) {
		k, v, _ := strings.Cut(tok, "=")
		switch k {
		case "kind":
			e.Kind = EntityKind(v)
		case "planes":
			p, err := ParsePlanes(v)
			if err != nil {
				return err
			}
			e.Planes = p
		case "sql_schema":
			e.SQLSchema = v
		case "sql_table":
			e.SQLTable = v
		case "datastore_db":
			e.DatastoreDB = v
		case "datastore_table":
			e.DatastoreTable = v
		case "tenant":
			col, mode, _ := strings.Cut(v, ":")
			e.Tenant = TenantSpec{Column: col, Isolated: true, RLS: mode == "rls"}
		case "domain":
			e.Catalog.Domain = v
		case "financial":
			e.Catalog.Financial = v == "true"
		case "retention":
			e.Catalog.Retention = strings.ReplaceAll(v, "%20", " ")
		case "freshness_ms":
			n, err := strconv.ParseUint(v, 10, 32)
			if err != nil {
				return fmt.Errorf("invalid freshness_ms %q", v)
			}
			e.Catalog.FreshnessTargetMS = uint32(n)
		case "accuracy":
			e.Catalog.Accuracy = v
		case "order_by":
			e.OrderBy = strings.Split(v, "+")
		case "version_col":
			e.VersionCol = v
		case "ttl":
			e.TTL = strings.ReplaceAll(v, "%20", " ")
		}
	}
	return nil
}

func applyFieldAnnotation(f *Field, meta string) error {
	for _, tok := range strings.Fields(meta) {
		k, v, _ := strings.Cut(tok, "=")
		switch k {
		case "name":
			f.Name = v
		case "type":
			f.Type = FieldType(v)
		case "pk":
			f.PrimaryKey = true
		case "nullable":
			f.Nullable = true
		case "unique":
			f.Unique = true
		case "index":
			f.Indexed = true
		case "version":
			f.Version = true
		case "timestamp":
			f.Timestamp = true
		case "partition":
			f.Partition = true
		case "order":
			n, err := strconv.Atoi(v)
			if err != nil {
				return fmt.Errorf("invalid order %q", v)
			}
			f.OrderRank = n
		case "sign":
			f.Sign = true
		case "tombstone":
			f.Tombstone = true
		case "pii":
			f.PII = true
		case "unit":
			f.Unit = v
		case "default":
			f.Default = v
		}
	}
	return nil
}

func zapTypeToFieldType(zt string) FieldType {
	switch strings.ToLower(zt) {
	case "bool":
		return TypeBool
	case "i8", "int8":
		return TypeInt8
	case "u8", "uint8":
		return TypeUint8
	case "i16", "int16":
		return TypeInt16
	case "u16", "uint16":
		return TypeUint16
	case "i32", "int32":
		return TypeInt32
	case "u32", "uint32":
		return TypeUint32
	case "i64", "int64":
		return TypeInt64
	case "u64", "uint64":
		return TypeUint64
	case "f32", "float32":
		return TypeFloat32
	case "f64", "float64":
		return TypeFloat64
	case "bytes", "data":
		return TypeBytes
	case "list<text>":
		return TypeStringArray
	case "text":
		return TypeString
	default:
		return TypeString
	}
}
